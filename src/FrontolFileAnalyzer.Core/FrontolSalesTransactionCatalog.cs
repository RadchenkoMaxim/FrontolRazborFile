    private static void Set(
        FieldDefinition[] fields,
        int number,
        string name,
        string dataType,
        string purpose,
        bool required = false,
        IReadOnlyDictionary<string, string>? values = null,
        Func<string, string?>? interpreter = null,
        bool allowUnknown = false) =>
        fields[number - 1] = F(number, name, dataType, purpose, required, values, interpreter, allowUnknown);

    private static IReadOnlyDictionary<string, string> Map(params (string Code, string Name)[] values) =>
        values.ToDictionary(item => item.Code, item => item.Name, StringComparer.Ordinal);

    private static string? InterpretDocumentInfo(string value)
    {
        var parts = value.Split('/');
        return parts.Length == 3
            ? $"Код РМ: {parts[0]} · смена: {parts[1]} · документ: {parts[2]}"
            : null;
    }
