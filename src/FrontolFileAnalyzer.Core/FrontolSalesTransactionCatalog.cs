    private static string CategoryFor(string code)
    {
        if (ProductTransactionCodes.Contains(code))
        {
            return "1|Продажи и товары";
        }

        if (code is "9" or "10" or "15" or "17" or "32" or "33" or "34" or "35" or "36" or "37" or "38" or "40" or "43" or "82" or "83" or "84" or "85" or "86" or "87")
        {
            return "2|Оплаты, скидки и бонусы";
        }

        if (code is "42" or "45" or "49" or "50" or "51" or "55" or "56" or "58" or "60" or "61" or "62" or "63" or "64" or "65" or "88" or "120" or "121")
        {
            return "3|Документы и смены";
        }

        return "4|Прочие транзакции";
    }

