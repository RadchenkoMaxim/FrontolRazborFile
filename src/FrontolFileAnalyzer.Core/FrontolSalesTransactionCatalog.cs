    public static IReadOnlyList<CommandDefinition> All { get; } = BuildDefinitions();

    private static readonly IReadOnlyDictionary<string, CommandDefinition> ByCode =
        All.ToDictionary(definition => definition.Name, StringComparer.Ordinal);

    public static bool TryGet(string? code, out CommandDefinition definition)
    {
        if (code is not null && ByCode.TryGetValue(code.Trim(), out var found))
        {
            definition = found;
            return true;
        }

        definition = null!;
        return false;
    }

    public static bool IsProductTransaction(string? code) =>
        code is not null && ProductTransactionCodes.Contains(code);

