    private static string? InterpretWeekdayFlags(string value)
    {
        if (string.IsNullOrEmpty(value))
        {
            return null;
        }

        string[] weekdayNames = ["Понедельник", "Вторник", "Среда", "Четверг", "Пятница", "Суббота", "Воскресенье"];
        var flags = value.Split(',', StringSplitOptions.TrimEntries);
        return string.Join(" · ", weekdayNames.Select((name, index) =>
            $"{name}: {(index < flags.Length ? FlagText(flags[index]) : "по умолчанию")}"));
    }
