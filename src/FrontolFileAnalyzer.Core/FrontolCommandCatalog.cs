    private static string? InterpretBarcodes(string value)
    {
        if (string.IsNullOrEmpty(value))
        {
            return null;
        }

        var barcodes = value.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        return barcodes.Length == 0 ? null : $"Штрихкодов: {barcodes.Length} · {string.Join(" · ", barcodes)}";
    }

    private static string? InterpretFlags(string value)
    {
        if (string.IsNullOrEmpty(value))
        {
            return null;
        }

        string[] names =
        [
            "Дробное количество", "Продажа", "Возврат", "Отрицательные остатки", "Без ввода количества",
            "Списание остатков", "Редактирование цены", "Ручной ввод количества", "Печать в документе",
            "Наливаемый товар", "Скидки", "Запрос цены", "Запрос штрихкода", "Округление", "Деление упаковки"
        ];
        var flags = value.Split(',', StringSplitOptions.TrimEntries);
        return string.Join(" · ", names.Select((name, index) =>
        {
            var flag = index < flags.Length ? flags[index] : "по умолчанию";
            return $"{index + 1}. {name}: {FlagText(flag)}";
        }));
    }

    private static string FlagText(string value) => value switch
    {
        "1" => "да",
        "0" => "нет",
        _ => value
    };

    private static string? WithUnit(string value, string label, string unit) =>
        string.IsNullOrEmpty(value) ? null : $"{label}: {value}{(string.IsNullOrEmpty(unit) ? "" : $" {unit}")}";

